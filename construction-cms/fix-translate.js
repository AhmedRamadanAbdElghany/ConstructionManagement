const fs = require('fs');
const path = require('path');

function walk(dir) {
    let results = [];
    const list = fs.readdirSync(dir);
    list.forEach(file => {
        const fullPath = path.join(dir, file);
        const stat = fs.statSync(fullPath);
        if (stat && stat.isDirectory()) {
            results = results.concat(walk(fullPath));
        } else if (fullPath.endsWith('.ts') || fullPath.endsWith('.html')) {
            results.push(fullPath);
        }
    });
    return results;
}

const files = walk('src/app');
let fixedCount = 0;

for (const file of files) {
    let content = fs.readFileSync(file, 'utf8');
    let original = content;

    // Replace the full-page loading spinners that use translate pipe with simple label
    // These were auto-generated by replace-loaders.js
    content = content.replace(
        /<app-loading-spinner\s+\[centered\]="true"\s+\[label\]="'common\.loading'\s+\|\s+translate"><\/app-loading-spinner>/g,
        '<app-loading-spinner [centered]="true"></app-loading-spinner>'
    );

    if (original !== content) {
        fs.writeFileSync(file, content, 'utf8');
        console.log('Simplified spinner in: ' + file);
        fixedCount++;
    }
}
console.log('Total simplified: ' + fixedCount);
